-- BillShield-managed credentials and history. This does not use Supabase Auth.
-- The server accesses these tables with a Supabase secret key after validating
-- the app's own opaque, database-backed session cookie.

create table if not exists public.billshield_users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique check (char_length(email) <= 254),
  display_name text not null default '' check (char_length(display_name) <= 100),
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.billshield_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.billshield_users (id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists billshield_sessions_user_idx on public.billshield_sessions (user_id);
create index if not exists billshield_sessions_expiry_idx on public.billshield_sessions (expires_at);

create table if not exists public.billshield_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.billshield_users (id) on delete cascade,
  title text not null default 'Bill review' check (char_length(title) <= 120),
  context text not null default '' check (char_length(context) <= 3000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);
create index if not exists billshield_conversations_user_updated_idx
  on public.billshield_conversations (user_id, updated_at desc);

create table if not exists public.billshield_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null,
  user_id uuid not null references public.billshield_users (id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null check (char_length(content) <= 6000),
  created_at timestamptz not null default now(),
  constraint billshield_message_owner_fk foreign key (conversation_id, user_id)
    references public.billshield_conversations (id, user_id) on delete cascade
);
create index if not exists billshield_messages_conversation_created_idx
  on public.billshield_messages (conversation_id, created_at);

create table if not exists public.billshield_auth_limits (
  identifier_hash text primary key,
  attempts integer not null default 0,
  window_started_at timestamptz not null default now(),
  blocked_until timestamptz
);

create or replace function public.billshield_auth_failure(p_identifier_hash text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_limit public.billshield_auth_limits%rowtype;
  checked_at timestamptz := now();
begin
  insert into public.billshield_auth_limits (identifier_hash, attempts, window_started_at)
  values (p_identifier_hash, 1, checked_at)
  on conflict (identifier_hash) do nothing;

  select * into current_limit
  from public.billshield_auth_limits
  where identifier_hash = p_identifier_hash
  for update;

  if current_limit.blocked_until is not null and current_limit.blocked_until > checked_at then
    return;
  end if;

  if current_limit.window_started_at < checked_at - interval '15 minutes' then
    update public.billshield_auth_limits
    set attempts = 1, window_started_at = checked_at, blocked_until = null
    where identifier_hash = p_identifier_hash;
    return;
  end if;

  if current_limit.attempts >= 9 then
    update public.billshield_auth_limits
    set attempts = 10,
        blocked_until = checked_at + interval '15 minutes'
    where identifier_hash = p_identifier_hash;
    return;
  end if;

  update public.billshield_auth_limits
  set attempts = current_limit.attempts + 1
  where identifier_hash = p_identifier_hash;
end;
$$;
revoke all on function public.billshield_auth_failure(text) from public, anon, authenticated;
grant execute on function public.billshield_auth_failure(text) to service_role;

/*
  The app checks blocked_until before password verification. This function
  records only failed attempts, so successful sign-ins don't consume the limit.
*/

alter table public.billshield_users enable row level security;
alter table public.billshield_sessions enable row level security;
alter table public.billshield_conversations enable row level security;
alter table public.billshield_messages enable row level security;
alter table public.billshield_auth_limits enable row level security;

revoke all on public.billshield_users, public.billshield_sessions,
  public.billshield_conversations, public.billshield_messages from anon, authenticated;
revoke all on public.billshield_auth_limits from anon, authenticated;
grant select, insert, update, delete on public.billshield_users,
  public.billshield_sessions, public.billshield_conversations,
  public.billshield_messages, public.billshield_auth_limits to service_role;
grant usage, select on sequence public.billshield_messages_id_seq to service_role;
